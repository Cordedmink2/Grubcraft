/// The biggest whole-pixel scale at which an icon fits `r` (0 when it can't
/// even be drawn at 1).
pub fn icon_scale(r: Rect) -> i32 {
    r.w.min(r.h) / ICON_CELLS
}

/// Draw `icon` in `color`, centred in `r`, at the largest whole scale that
/// fits (nothing if `r` is under 12 pixels a side). Runs of cells in a row
/// are merged, so an icon costs a few dozen quads.
pub fn icon(draw: &mut DrawList, r: Rect, icon: Icon, color: Color) {
    let scale = icon_scale(r);
    if scale < 1 || icon == Icon::None {
        return;
    }
    let side = ICON_CELLS * scale;
    let (x0, y0) = (r.x + (r.w - side) / 2, r.y + (r.h - side) / 2);
    for (row, line) in icon.rows().iter().enumerate() {
        let bytes = line.as_bytes();
        let mut col = 0;
        while col < bytes.len() {
            if bytes[col] != b'#' {
                col += 1;
                continue;
            }
            let start = col;
            while col < bytes.len() && bytes[col] == b'#' {
                col += 1;
            }
            draw.rect(
                Rect::new(
                    x0 + start as i32 * scale,
                    y0 + row as i32 * scale,
                    (col - start) as i32 * scale,
                    scale,
                ),
                color,
            );
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_icon_is_a_12_by_12_pattern_that_draws_something() {
        for i in Icon::ALL {
            let rows = i.rows();
            assert!(
                rows.iter().all(|r| r.len() == 12),
                "{i:?} has a row that is not 12 cells wide"
            );
            assert!(
                rows.iter()
                    .all(|r| r.bytes().all(|b| b == b'#' || b == b'.')),
                "{i:?}"
            );
            let mut d = DrawList::default();
            icon(&mut d, Rect::new(0, 0, 24, 24), i, [1, 2, 3, 255]);
            assert!(!d.quads.is_empty(), "{i:?} drew nothing");
        }
    }

    #[test]
    fn an_icon_scales_in_whole_pixels_and_stays_in_its_rect() {
        let r = Rect::new(10, 20, 30, 40);
        assert_eq!(icon_scale(r), 2);
        let mut d = DrawList::default();
        icon(&mut d, r, Icon::Hold, [9; 4]);
        for q in &d.quads {
            let q = Rect::new(
                i32::from(q.pos[0]),
                i32::from(q.pos[1]),
                i32::from(q.size[0]),
                i32::from(q.size[1]),
            );
            assert!(q.intersect(r) == Some(q), "{q:?} leaves {r:?}");
        }
        // Too small: nothing.
        let mut d = DrawList::default();
        icon(&mut d, Rect::new(0, 0, 11, 11), Icon::Hold, [9; 4]);
        assert!(d.quads.is_empty());
        icon(&mut d, r, Icon::None, [9; 4]);
        assert!(d.quads.is_empty());
    }
}
