#!/usr/bin/env python3
"""Rasterise printable ASCII from DejaVu Sans Mono into 8x16 one-bit glyphs
for the dev overlay, writing crates/gc_render/src/debug_font.rs.

Run from the repository root: python3 scripts/gen_debug_font.py [path/to/DejaVuSansMono.ttf]
Needs Pillow. The output is committed; rerun only to change the font.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

W, H = 8, 16
FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
font = ImageFont.truetype(FONT, 13)
ascent, _ = font.getmetrics()

rows = []
for code in range(32, 127):
    img = Image.new("L", (W, H), 0)
    ImageDraw.Draw(img).text((0, 13 - ascent), chr(code), font=font, fill=255)
    glyph = []
    for y in range(H):
        bits = 0
        for x in range(W):
            if img.getpixel((x, y)) >= 110:
                bits |= 0x80 >> x
        glyph.append(bits)
    rows.append((code, glyph))

out = [
    "//! 8x16 one-bit glyphs for printable ASCII (32..=126), for the dev overlay.",
    "//! Generated by scripts/gen_debug_font.py from DejaVu Sans Mono",
    "//! (Bitstream Vera / DejaVu licence, see docs/dependencies.md). Do not edit.",
    "",
    "pub const GLYPH_WIDTH: u32 = 8;",
    "pub const GLYPH_HEIGHT: u32 = 16;",
    "pub const FIRST_CHAR: u8 = 32;",
    "",
    "/// One `u8` per row, most significant bit leftmost.",
    "#[rustfmt::skip]",
    "pub static GLYPHS: [[u8; 16]; 95] = [",
]
for code, glyph in rows:
    label = "space" if code == 32 else repr(chr(code))
    out.append("    [" + ", ".join(f"0x{b:02x}" for b in glyph) + f"], // {label}")
out.append("];")
open("crates/gc_render/src/debug_font.rs", "w").write("\n".join(out) + "\n")
print("wrote crates/gc_render/src/debug_font.rs")
